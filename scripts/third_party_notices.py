"""Writes THIRD-PARTY-NOTICES.txt: the licences of the crates compiled into
the exes for Windows (knurl-probe.exe, the Knurl Probe app, and
knurl-probe-cli.exe, the command line), which the release zip must carry (MIT, Apache-2.0 and similar licences
ask for their text with binary copies).

The list is what `cargo tree` resolves for both packages on the Windows target with
the locked versions and the features actually enabled: normal dependencies
only, without proc-macros (build-only crates are not in the binary). Crate
data and sources come from `cargo metadata`. Each crate's own LICENSE*,
LICENCE*, COPYING* and NOTICE* files (and REUSE LICENSES/ folders) are copied
as they are; a crate that ships none gets the upstream text kept in
scripts/licence-overrides/<name>-<version>-LICENSE. --check also fails when a
crate whose licence needs its text (no Apache-2.0 or BSL-1.0 choice) has
neither.

Usage:
  python scripts/third_party_notices.py          # writes the file
  python scripts/third_party_notices.py --check  # exit 1 if it is out of date
"""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.txt"
TARGET = "x86_64-pc-windows-msvc"
PREFIXES = ("license", "licence", "copying", "notice")
OVERRIDES = ROOT / "scripts" / "licence-overrides"
# A crate offering one of these needs no copied text in a binary-only copy
# (Apache-2.0: the standard text is included; BSL-1.0 waives it for binaries).
TEXT_NOT_NEEDED = ("Apache-2.0", "BSL-1.0")
SEPARATOR = "#" * 78


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
        cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8",
    ).stdout
    return json.loads(out)


# The packages whose binaries ship.
PACKAGES = ("knurl-probe", "knurl-probe-app")


def linked():
    """(name, version) of the crates linked into the shipped binaries, with the
    features the build really enables (cargo metadata's resolve graph also
    lists optional dependencies nobody turns on)."""
    found = set()
    for package in PACKAGES:
        out = subprocess.run(
            ["cargo", "tree", "-p", package, "-e", "normal,no-proc-macro", "--target", TARGET,
             "--prefix", "none", "-f", "{p}", "--locked"],
            cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8",
        ).stdout
        for line in out.splitlines():
            parts = line.replace(" (*)", "").split()
            if len(parts) >= 2 and parts[1].startswith("v"):
                found.add((parts[0], parts[1][1:]))
    return found


def shipped(meta):
    """Packages linked into the shipped binaries, workspace crates excluded."""
    members = set(meta["workspace_members"])
    keep = linked()
    pkgs = [p for p in meta["packages"] if p["id"] not in members and (p["name"], p["version"]) in keep]
    return sorted(pkgs, key=lambda p: (p["name"], p["version"]))


def licence_files(pkg):
    folder = pathlib.Path(pkg["manifest_path"]).parent
    files = [f for f in sorted(folder.iterdir()) if f.is_file() and f.name.lower().startswith(PREFIXES)]
    # REUSE layout (Slint, for example): one file per licence in LICENSES/.
    for sub in sorted(folder.iterdir()):
        if sub.is_dir() and sub.name.lower() == "licenses":
            files += [f for f in sorted(sub.iterdir()) if f.is_file()]
    override = OVERRIDES / f"{pkg['name']}-{pkg['version']}-LICENSE"
    if not files and override.exists():
        files = [override]
    return [(f.name, f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()) for f in files]


def render(pkgs):
    """Each distinct licence text once, with the crates that ship it."""
    texts = {}  # text -> (file name, [crates])
    missing = []
    for p in pkgs:
        files = licence_files(p)
        if not files:
            missing.append(p)
        for name, text in files:
            texts.setdefault(text, (name, []))[1].append(f"{p['name']} {p['version']}")
    lines = [
        "Third-party notices for knurl-probe (the command line and the Knurl Probe app)",
        "",
        "knurl-probe is licensed under MIT OR Apache-2.0 (LICENSE-MIT, LICENSE-APACHE).",
        "It includes the crates listed below, under their own licences. The Slint",
        "crates (the app's interface) are used under the Slint Royalty-free",
        "Licence 2.0 (LicenseRef-Slint-Royalty-free-2.0), whose attribution is the",
        "\"Made with Slint\" badge on the app's first screen. Each distinct licence or",
        "notice text the crates ship is reproduced once, followed by the crates",
        "that ship it. Generated by scripts/third_party_notices.py.",
        "",
        f"{len(pkgs)} crates:",
        "",
    ]
    lines += [f"- {p['name']} {p['version']}: {p.get('license') or 'see its licence file'}" for p in pkgs]
    if missing:
        lines += [
            "",
            "These crates ship no licence file of their own; the standard text of the",
            "licence they name is among the texts below:",
        ]
        lines += [f"- {p['name']} {p['version']}: {p.get('license') or 'not declared'}" for p in missing]
    for text, (name, crates) in sorted(texts.items(), key=lambda kv: (kv[1][0].lower(), kv[1][1][0])):
        lines += ["", SEPARATOR, f"{name}, shipped by: {', '.join(crates)}", "", text]
    needs_text = [
        p["name"] for p in missing
        if not any(choice in (p.get("license") or "") for choice in TEXT_NOT_NEEDED)
    ]
    return "\n".join(lines) + "\n", needs_text


def main():
    text, missing = render(shipped(metadata()))
    if missing:
        print("these crates need their licence text in scripts/licence-overrides/: " + ", ".join(missing))
        if "--check" in sys.argv:
            return 1
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("THIRD-PARTY-NOTICES.txt is out of date: run python scripts/third_party_notices.py")
            return 1
        print("THIRD-PARTY-NOTICES.txt is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
